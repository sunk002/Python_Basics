#     ((1, 25), 'eth 1/101/1/25'),
#     ((1, 45), 'eth 1/101/1/45'),
#     ((2, 8),  'eth 1/101/2/8'),    # f('eth 1/101/2/8')  → (2, 8)
# ]
#第 2 步：按左边的键排序
