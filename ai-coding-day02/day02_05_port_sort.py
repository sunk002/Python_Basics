import re

port_list = [
    'eth 1/101/1/42',
    'eth 1/101/1/26',
    'eth 1/101/1/23',
    'eth 1/101/1/7',
    'eth 1/101/2/46',
    'eth 1/101/1/34',
    'eth 1/101/1/18',
    'eth 1/101/1/13',
    'eth 1/101/1/32',
    'eth 1/101/1/25',
    'eth 1/101/1/45',
    'eth 1/101/2/8',
]

port_list.sort(key=lambda x: tuple(map(int, re.search(r'(\d+)/(\d+)$', x).groups())))

#  $匹配字符串结尾，x形参；
#  re.search(r'(\d+)/(\d+)$', x).groups()  捕获1/42，将所有端口后两位放到捕获组('1','42')
#  map(int,..) 批量转换为整数，只准备不输出 1,42
#  tuple 输出整数元组(1,42)

# 第 1 步执行完，键列表实际是：
# [
#     ((1, 42), 'eth 1/101/1/42'),   # f('eth 1/101/1/42') → (1, 42)
#     ((1, 26), 'eth 1/101/1/26'),   # f('eth 1/101/1/26') → (1, 26)
#     ((1, 23), 'eth 1/101/1/23'),
#     ((1, 7),  'eth 1/101/1/7'),    # f('eth 1/101/1/7')  → (1, 7)
#     ((2, 46), 'eth 1/101/2/46'),
#     ((1, 34), 'eth 1/101/1/34'),
#     ((1, 18), 'eth 1/101/1/18'),
#     ((1, 13), 'eth 1/101/1/13'),
